"""Render the metric markers in the living documents from outputs/metrics.json.

    python src/reporting/render_docs.py                      rewrite every stale marker in place
    python src/reporting/render_docs.py --check              change nothing; exit 1 if any marker is stale, unknown or malformed
    python src/reporting/render_docs.py --run-date 2026-10-18  also require that metrics.json was built for that run
    python src/reporting/render_docs.py --metrics PATH --root PATH   (tests / other trees)
    python src/reporting/render_docs.py --list               show the files that carry markers and the exclusion list

Marker syntax (readable in Markdown and on GitHub; an HTML comment is invisible when rendered):

    <!--m:core_n-->720<!--/m-->                   inner text := the registry's `display` for that key
    <!--m:vienna_share_core:pct1-->47.6 %<!--/m-->  an explicit format after a colon (see metrics_registry.py: pct0 pct1 int f1 eur_k ...)
    <!--m:_meta.demand_vintage-->2026-09-16<!--/m-->   data vintages: _meta.demand_vintage, _meta.supply_vintage, _meta.supply_vintage_span,
                                                       _meta.stale_after_demand, _meta.stale_after_supply, _meta.week_id, _meta.run_date
    <!--m:_meta.demand_vintage:+91d-->2026-12-16<!--/m-->   date arithmetic: a date plus N days (also `ym` = year-month)

The renderer replaces ONLY the inner text. An unknown key, an unknown format, an unterminated marker or a marker
in an excluded file is an error (exit 1) — a document must never keep a number that nothing computes. It is
idempotent: a second run changes nothing. Line endings (CRLF in a Windows working tree, LF in git) are preserved
byte for byte; markers inside fenced code blocks and inline `code` are ignored so the syntax can be documented.

Weekly order (the orchestrator): metrics_registry.py -> render_docs.py -> update_knowledge.py.

EXCLUDE (never rendered; a marker found there is an error). These files are dated historical records or "as of"
audits: their numbers are frozen on purpose, because rewriting them would falsify what was true when they were written.
"""
from __future__ import annotations

import argparse
import fnmatch
import json
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from metrics_registry import KNOWN_FORMATS, fmt_value  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]

# Frozen by design. Each entry: path or glob (posix, relative to the repository root) -> reason.
EXCLUDE: dict[str, str] = {
    "DECISION_LOG.md": "dated decision records (D-001 ...): each entry states what was true and decided on its date",
    "PROGRESS.md": "dated working log; status history, not current evidence",
    "PUBLICATION_DECISION.md": "dated publication-readiness conclusions",
    "docs/legal-and-publication-audit.md": "audit as of the dates its clauses were fetched (2026-09-16/17)",
    "docs/original-specification-audit.md": "audit of the original brief as of 2026-09",
    "docs/question-coverage-audit.md": "audit as of its date; counts are a historical coverage statement",
    "docs/supply-research-audit.md": "audit as of its date",
    "docs/supply-completeness-audit.md": "audit as of its date",
    "docs/open-questions.md": "register 'as of 2026-09-30' (24 entries ...); entries are dated closings, not live metrics",
    "docs/kaggle-terms-review.md": "dated terms review (D-030)",
    "docs/research-landscape.md": "literature review, not snapshot-derived",
    "docs/labelling-protocol.md": "protocol of a dated labelling exercise",
    "docs/visual-decision-board.md": "generated by embed_figures.py from visual_questions.json (its answers are computed at render time)",
    "archive/**": "archived material",
    "library_strategy/**": "private strategy notes derived at a date",
    "data/**": "private data",
    "outputs/**": "generated outputs (reports/digest.txt etc.)",
    "logs/**": "logs",
    ".git/**": "git",
    "**/node_modules/**": "dependencies",
}
SKIP_DIRS = {".git", "node_modules", "__pycache__", "archive", "data", "logs", "outputs", ".pytest_cache", ".venv", "venv"}

MARKER_RE = re.compile(r"<!--m:([A-Za-z_][A-Za-z0-9_.]*)(?::([A-Za-z0-9_+]+))?-->([^\n]*?)<!--/m-->")
OPEN_RE = re.compile(r"<!--m:")
FENCE_RE = re.compile(r"^(```|~~~).*?^\1[^\n]*$", re.S | re.M)
INLINE_RE = re.compile(r"`[^`\n]+`")


def masked_spans(text: str) -> list[tuple[int, int]]:
    spans = [m.span() for m in FENCE_RE.finditer(text)]
    spans += [m.span() for m in INLINE_RE.finditer(text)]
    return spans


def in_spans(pos: int, spans: list[tuple[int, int]]) -> bool:
    return any(a <= pos < b for a, b in spans)


def is_excluded(rel: str) -> str | None:
    for pattern, reason in EXCLUDE.items():
        if rel == pattern or fnmatch.fnmatch(rel, pattern):
            return reason
    return None


def resolve(key: str, fmt: str | None, metrics: dict) -> str:
    """The text a marker must carry. Raises KeyError / ValueError for an unknown key or format."""
    if fmt is not None and not (fmt in KNOWN_FORMATS or re.fullmatch(r"\+\d+d", fmt)):
        raise ValueError(f"unknown format {fmt!r} (known: {' '.join(KNOWN_FORMATS)} and +Nd)")
    if key.startswith("_meta."):
        meta = metrics.get("_meta") or {}
        name = key[len("_meta."):]
        if name not in meta:
            raise KeyError(f"unknown meta key {key!r}")
        value = meta[name]
        return str(value) if fmt is None else fmt_value(value, "date" if re.search(r"^\d{4}-\d\d-\d\d", str(value)) else "text", fmt)
    if key not in metrics or key == "_meta":
        raise KeyError(f"unknown metric key {key!r}")
    entry = metrics[key]
    return entry["display"] if fmt is None else fmt_value(entry["value"], entry["unit"], fmt)


def render_text(text: str, metrics: dict) -> tuple[str, dict]:
    """Return (new_text, stats). stats: markers, stale (list of (key, old, new)), errors (list of strings)."""
    stats = {"markers": 0, "stale": [], "errors": []}
    spans = masked_spans(text)
    out, last = [], 0
    consumed_starts = set()
    for m in MARKER_RE.finditer(text):
        if in_spans(m.start(), spans):
            continue
        consumed_starts.add(m.start())
        key, fmt, old = m.group(1), m.group(2), m.group(3)
        stats["markers"] += 1
        try:
            new = resolve(key, fmt, metrics)
        except (KeyError, ValueError) as exc:
            line = text.count("\n", 0, m.start()) + 1
            stats["errors"].append(f"line {line}: {exc.args[0] if exc.args else exc}")
            continue
        if new != old:
            stats["stale"].append((key, old, new))
        out.append(text[last:m.start(3)])
        out.append(new)
        last = m.end(3)
    out.append(text[last:])
    # every opening token must belong to a well-formed marker
    for m in OPEN_RE.finditer(text):
        if in_spans(m.start(), spans):
            continue
        if m.start() not in consumed_starts:
            line = text.count("\n", 0, m.start()) + 1
            stats["errors"].append(f"line {line}: malformed or unterminated marker (needs <!--m:key-->text<!--/m--> on one line)")
    return "".join(out), stats


def iter_markdown(root: Path):
    """Every *.md below `root`, pruning data/archive/outputs/... (private or generated trees) before descending."""
    found = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        for name in filenames:
            if name.lower().endswith(".md"):
                path = Path(dirpath) / name
                found.append((path, path.relative_to(root).as_posix()))
    yield from sorted(found, key=lambda item: item[1])


def load_metrics(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def process(root: Path, metrics: dict, *, check: bool) -> dict:
    result = {"files": {}, "errors": [], "stale_total": 0, "markers_total": 0, "changed": []}
    for path, rel in iter_markdown(root):
        raw = path.read_bytes()
        try:
            text = raw.decode("utf-8")
        except UnicodeDecodeError:
            continue
        if "<!--m:" not in text:
            continue
        reason = is_excluded(rel)
        if reason:
            result["errors"].append(f"{rel}: contains metric markers but is on the EXCLUDE list ({reason})")
            continue
        new_text, stats = render_text(text, metrics)
        result["files"][rel] = stats
        result["markers_total"] += stats["markers"]
        result["stale_total"] += len(stats["stale"])
        for err in stats["errors"]:
            result["errors"].append(f"{rel}: {err}")
        if new_text != text and not stats["errors"]:
            result["changed"].append(rel)
            if not check:
                path.write_bytes(new_text.encode("utf-8"))
    return result


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Render <!--m:key-->...<!--/m--> markers in the living documents from outputs/metrics.json.")
    ap.add_argument("--check", action="store_true", help="change nothing; exit 1 if any marker is stale, unknown or malformed")
    ap.add_argument("--run-date", help="ISO date of the weekly run; with it the registry must have been built for the same run")
    ap.add_argument("--metrics", default=None, help="registry path (default outputs/metrics.json)")
    ap.add_argument("--root", default=str(ROOT), help="repository root (default: this repository)")
    ap.add_argument("--list", action="store_true", help="list marker-bearing files and the EXCLUDE list, then exit")
    args = ap.parse_args(argv)
    root = Path(args.root)
    if args.list:
        print("EXCLUDE (frozen by design):")
        for pat, why in EXCLUDE.items():
            print(f"  {pat:42s} {why}")
        for path, rel in iter_markdown(root):
            text = path.read_text(encoding="utf-8", errors="replace")
            n = len(MARKER_RE.findall(text))
            if n:
                print(f"  {rel:55s} {n} markers")
        return 0
    metrics_path = Path(args.metrics) if args.metrics else root / "outputs" / "metrics.json"
    try:
        metrics = load_metrics(metrics_path)
    except (OSError, ValueError) as exc:
        print(f"cannot read the registry {metrics_path}: {exc} — run src/reporting/metrics_registry.py first", file=sys.stderr)
        return 1
    problems: list[str] = []
    if args.run_date and (metrics.get("_meta") or {}).get("run_date") != args.run_date:
        problems.append(f"registry was built for run_date {(metrics.get('_meta') or {}).get('run_date')!r}, not {args.run_date!r}: "
                        "run metrics_registry.py --run-date first")
    result = process(root, metrics, check=args.check)
    for rel, st in result["files"].items():
        flag = f"  STALE x{len(st['stale'])}" if st["stale"] else ""
        print(f"{rel:55s} {st['markers']:4d} markers{flag}")
    problems += result["errors"]
    if args.check:
        for rel, st in result["files"].items():
            for key, old, new in st["stale"]:
                problems.append(f"{rel}: stale marker {key}: {old!r} should be {new!r}")
    verb = "would change" if args.check else "updated"
    print(f"\n{result['markers_total']} markers in {len(result['files'])} files; {result['stale_total']} stale; "
          f"{verb}: {len(result['changed'])} file(s); {len(problems)} problem(s)")
    for p in problems:
        print("  PROBLEM " + p, file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
